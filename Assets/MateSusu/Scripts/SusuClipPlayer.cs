using UnityEngine;
using UnityEngine.Animations;
using UnityEngine.Playables;

/// <summary>
/// Plays ready-made humanoid AnimationClips on Susu on top of the normal Mate Engine Animator.
/// The clips go through a second playable output whose weight fades in and out, so the
/// original controller (idle, blink, drag, sleep...) is never replaced or edited.
/// Two mixer slots let one motion cross-fade into the next.
/// </summary>
public class SusuClipPlayer : MonoBehaviour
{
    public static SusuClipPlayer Instance { get; private set; }

    /// <summary>Animator bools that mean Mate Engine is doing something more important than a gesture.</summary>
    static readonly string[] BusyFlags =
    {
        "isDragging", "isDancing", "isSitting", "isWindowSit", "isTaskbarSit", "IsSleeping",
        "isBigScreen", "isBigScreenSaver", "isBigScreenAlarm", "HideLeft", "HideRight",
        "isCustomDancing", "isWaitingForDancing", // custom dance (Dance Player): never move over it
    };

    public bool IsPlaying => graph.IsValid() && outTarget > 0f;

    PlayableGraph graph;
    AnimationPlayableOutput output;
    AnimationMixerPlayable mixer;
    readonly AnimationClipPlayable[] slots = new AnimationClipPlayable[2];
    readonly float[] slotWeight = new float[2];
    Animator bound;
    int current = -1;
    float outWeight, outTarget, fadeTime = 0.35f, stopAt;

    void Awake() { Instance = this; }

    void OnDestroy()
    {
        DestroyGraph();
        if (Instance == this) Instance = null;
    }

    public static Animator FindAvatarAnimator()
    {
        foreach (var a in FindObjectsByType<Animator>(FindObjectsSortMode.None))
            if (a.isActiveAndEnabled && a.avatar != null && a.isHuman && a.runtimeAnimatorController != null)
                return a;
        return null;
    }

    /// <summary>True while Mate Engine is dragging, dancing, sitting, sleeping, hiding...</summary>
    public static bool AvatarBusy(Animator a)
    {
        if (a == null) return true;
        foreach (var p in a.parameters)
            if (p.type == AnimatorControllerParameterType.Bool && System.Array.IndexOf(BusyFlags, p.name) >= 0 && a.GetBool(p.nameHash))
                return true;
        return false;
    }

    /// <summary>Play <paramref name="clip"/> from <paramref name="start"/> seconds for <paramref name="duration"/> real seconds (≤0 = to the end).</summary>
    public bool Play(AnimationClip clip, float start = 0f, float duration = 0f, float fade = 0.35f, float speed = 1f, bool footIK = true)
    {
        if (clip == null || !EnsureGraph() || AvatarBusy(bound)) return false;
        if (speed <= 0.01f) speed = 1f;

        int next = current < 0 ? 0 : 1 - current;
        if (slots[next].IsValid())
        {
            graph.Disconnect(mixer, next);
            slots[next].Destroy();
        }
        var cp = AnimationClipPlayable.Create(graph, clip);
        cp.SetApplyFootIK(footIK); // off for clips saved without foot goals, or the feet get pulled to the origin
        cp.SetSpeed(speed);
        cp.SetTime(start);
        cp.SetTime(start); // twice, so no root-motion delta is generated by the jump
        graph.Connect(cp, 0, mixer, next);
        slots[next] = cp;

        // Nothing visible yet: start the new slot at full weight and let the output fade in.
        if (outWeight <= 0.01f)
        {
            slotWeight[next] = 1f;
            slotWeight[1 - next] = 0f;
        }
        current = next;
        fadeTime = Mathf.Max(0.05f, fade);
        outTarget = 1f;
        stopAt = Time.time + (duration > 0f ? duration : Mathf.Max(0.1f, (clip.length - start) / speed));
        ApplyWeights();
        return true;
    }

    public void Stop() { outTarget = 0f; }

    bool EnsureGraph()
    {
        var animator = FindAvatarAnimator();
        if (animator == null) return false;
        if (graph.IsValid() && bound == animator) return true;

        DestroyGraph();
        bound = animator;
        graph = PlayableGraph.Create("SusuClipPlayer");
        graph.SetTimeUpdateMode(DirectorUpdateMode.GameTime);
        mixer = AnimationMixerPlayable.Create(graph, 2);
        output = AnimationPlayableOutput.Create(graph, "Susu", animator);
        output.SetSourcePlayable(mixer);
        output.SetWeight(0f);
        graph.Play();
        outWeight = 0f;
        current = -1;
        return true;
    }

    void DestroyGraph()
    {
        if (graph.IsValid()) graph.Destroy();
        slots[0] = slots[1] = default;
        slotWeight[0] = slotWeight[1] = 0f;
        current = -1;
        outWeight = outTarget = 0f;
        bound = null;
    }

    void Update()
    {
        if (!graph.IsValid()) return;
        if (bound == null || !bound.isActiveAndEnabled) { DestroyGraph(); return; } // avatar was swapped

        if (outTarget > 0f && (Time.time >= stopAt - fadeTime || AvatarBusy(bound))) outTarget = 0f;

        float step = Time.deltaTime / fadeTime;
        for (int i = 0; i < 2; i++)
            slotWeight[i] = Mathf.MoveTowards(slotWeight[i], i == current ? 1f : 0f, step);
        outWeight = Mathf.MoveTowards(outWeight, outTarget, step);
        ApplyWeights();

        if (outWeight <= 0f && outTarget <= 0f) DestroyGraph();
    }

    void ApplyWeights()
    {
        float sum = slotWeight[0] + slotWeight[1];
        for (int i = 0; i < 2; i++)
            mixer.SetInputWeight(i, sum > 0f ? slotWeight[i] / sum : 0f);
        output.SetWeight(Mathf.SmoothStep(0f, 1f, outWeight));
    }
}
